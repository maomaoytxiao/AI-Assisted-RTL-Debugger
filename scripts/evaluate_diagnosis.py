#!/usr/bin/env python3
"""Deterministically score saved AI diagnosis reports (make eval).

Inputs:
  reports/<exp>.json     - structured diagnosis written by the AI agent
  faults/faults.json     - ground truth (never shown to the agent)
  build/debug/<exp>/     - the bundle the agent investigated (from make debug-data)

For every experiment this script:
  1. re-executes every waveform query cited as evidence against the
     experiment's waves.db and checks the reported values match exactly;
  2. checks the reported first failure (time, cycle) against sim.log and the
     clock edges in the database;
  3. compares the suspected location (file + line) and signal with the
     injected fault.

A diagnosis is counted as correct when location AND signal match. The script
never generates diagnoses; a missing report is reported as missing.

Outputs: reports/evaluation.json, reports/evaluation.md, and an
auto-generated "Evaluation" section appended to each reports/<exp>.md.
Exit status: 1 if a report is missing/malformed or cites evidence that does
not reproduce, else 0 (an incorrect diagnosis is a result, not an error).
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from waveform_query import WaveformDB, WaveformQueryError   # noqa: E402
from fault_campaign import (load_faults, parse_log, rising_edges,  # noqa: E402
                            cycle_of, DEBUG_DIR)

REPORTS = os.environ.get("EVAL_REPORTS_DIR", os.path.join(ROOT, "reports"))
EVAL_MARK = "<!-- EVALUATION: generated by `make eval`, not by the debugging agent -->"


def accepted_lines(rtl_path, fault):
    """Lines of the injected block (in the buggy file) that contain a marker."""
    with open(rtl_path) as f:
        text = f.read()
    repl = fault["patch"]["replace"]
    pos = text.find(repl)
    if pos < 0:
        raise SystemExit("injected block not found in %s" % rtl_path)
    first = text.count("\n", 0, pos) + 1
    lines = repl.rstrip("\n").split("\n")
    return sorted(first + i for i, l in enumerate(lines)
                  if any(m in l for m in fault["root_cause_line_markers"]))


def norm_signal(s):
    s = (s or "").strip().split(".")[-1]
    return re.sub(r"\[.*\]$", "", s).strip()


def verify_evidence(db, ev):
    tool = ev.get("tool")
    try:
        if tool == "value":
            got = db.get_value_at_time(ev["signal"], ev["time"])["value"]
            ok = got == ev.get("observed_value")
            return ok, None if ok else "actual value %r" % got
        if tool == "history":
            h = db.get_signal_history(ev["signal"], ev["start"], ev["end"],
                                      max_events=100000)
            got = [[c["time"], c["value"]] for c in h["changes"]]
            want = [list(x) for x in ev.get("observed_changes", [])]
            ok = got == want
            return ok, None if ok else "actual changes %s" % got[:12]
        return False, "unknown tool %r" % tool
    except (KeyError, WaveformQueryError, ValueError) as e:
        return False, "%s: %s" % (type(e).__name__, e)


def evaluate(fault):
    exp = fault["experiment"]
    res = {"experiment": exp, "fault_id": fault["fault_id"]}
    rpath = os.path.join(REPORTS, exp + ".json")
    bundle = os.path.join(DEBUG_DIR, exp)
    if not os.path.isfile(rpath):
        res["status"] = "missing report"
        return res
    try:
        with open(rpath) as f:
            rep = json.load(f)
        rc, ff, evidence = rep["root_cause"], rep["first_failure"], rep["evidence"]
    except (ValueError, KeyError) as e:
        res["status"] = "malformed report: %s" % e
        return res

    rtl = os.path.join(bundle, "rtl", "sync_fifo.sv")
    acc = accepted_lines(rtl, fault)
    log = parse_log(os.path.join(bundle, "sim.log"))
    with WaveformDB(os.path.join(bundle, "waves.db")) as db:
        edges = rising_edges(db)
        checks = []
        for ev in evidence:
            ok, why = verify_evidence(db, ev)
            checks.append({"tool": ev.get("tool"), "signal": ev.get("signal"),
                           "time": ev.get("time", [ev.get("start"), ev.get("end")]),
                           "verified": ok, "problem": why})
    true_first = log["first_error"]
    true_cycle = cycle_of(edges, true_first["time"])

    file_ok = os.path.normpath(os.path.join(ROOT, rc.get("file", ""))) == os.path.normpath(rtl)
    line_ok = rc.get("line") in acc
    sig_ok = norm_signal(rc.get("signal")) in fault["root_cause_signals"]
    res.update({
        "status": "evaluated",
        "reported_location": "%s:%s" % (rc.get("file"), rc.get("line")),
        "accepted_lines": acc,
        "location_match": bool(file_ok and line_ok),
        "reported_signal": rc.get("signal"),
        "accepted_signals": fault["root_cause_signals"],
        "signal_match": sig_ok,
        "diagnosis_correct": bool(file_ok and line_ok and sig_ok),
        "first_failure_reported": {"time": ff.get("time"), "cycle": ff.get("cycle")},
        "first_failure_actual": {"time": true_first["time"], "cycle": true_cycle,
                                 "test": true_first["test"], "check": true_first["check"]},
        "first_failure_match": (ff.get("time") == true_first["time"]
                                and ff.get("cycle") == true_cycle),
        "evidence_total": len(checks),
        "evidence_verified": sum(c["verified"] for c in checks),
        "evidence_checks": checks,
        "confidence": rep.get("confidence"),
        "injected_fault": fault["description"],
    })
    return res


def md_section(r):
    if r["status"] != "evaluated":
        return "**Status:** %s\n" % r["status"]
    yn = lambda b: "yes" if b else "**no**"
    out = [
        "| Criterion | Result |", "|---|---|",
        "| Injected fault (ground truth) | %s (`%s`) |" % (r["injected_fault"], r["fault_id"]),
        "| Reported location | `%s` (accepted lines: %s) |" % (r["reported_location"], r["accepted_lines"]),
        "| Location matches | %s |" % yn(r["location_match"]),
        "| Reported signal | `%s` (accepted: %s) |" % (r["reported_signal"], ", ".join(r["accepted_signals"])),
        "| Signal matches | %s |" % yn(r["signal_match"]),
        "| **Diagnosis correct** | %s |" % yn(r["diagnosis_correct"]),
        "| First failure (reported / actual) | t=%s cycle=%s / t=%s cycle=%s |" % (
            r["first_failure_reported"]["time"], r["first_failure_reported"]["cycle"],
            r["first_failure_actual"]["time"], r["first_failure_actual"]["cycle"]),
        "| First failure matches | %s |" % yn(r["first_failure_match"]),
        "| Evidence entries re-verified against waves.db | %d / %d |" % (
            r["evidence_verified"], r["evidence_total"]),
        "| Agent-stated confidence | %s |" % r["confidence"],
    ]
    bad = [c for c in r["evidence_checks"] if not c["verified"]]
    for c in bad:
        out.append("\nUnverified evidence: %s %s @ %s: %s" % (c["tool"], c["signal"], c["time"], c["problem"]))
    return "\n".join(out) + "\n"


def main():
    faults = load_faults()
    results = [evaluate(f) for f in faults]
    evaluated = [r for r in results if r["status"] == "evaluated"]
    summary = {
        "injected_faults": len(faults),
        "reports_found": len(evaluated),
        "correct_diagnoses": sum(r["diagnosis_correct"] for r in evaluated),
        "incorrect_diagnoses": [r["experiment"] for r in evaluated if not r["diagnosis_correct"]],
        "first_failure_matches": sum(r["first_failure_match"] for r in evaluated),
        "evidence_verified": sum(r["evidence_verified"] for r in evaluated),
        "evidence_total": sum(r["evidence_total"] for r in evaluated),
        "results": results,
    }
    with open(os.path.join(REPORTS, "evaluation.json"), "w") as f:
        json.dump(summary, f, indent=2)

    md = ["# Milestone 3 evaluation (generated by `make eval`)", "",
          "Deterministic comparison of saved AI diagnosis reports with the "
          "ground truth in `faults/faults.json`. No LLM is involved in this step.", "",
          "| Experiment | Fault | Location | Signal | Diagnosis | First failure | Evidence verified |",
          "|---|---|---|---|---|---|---|"]
    for r in results:
        if r["status"] != "evaluated":
            md.append("| %s | %s | - | - | %s | - | - |" % (r["experiment"], r["fault_id"], r["status"]))
            continue
        md.append("| %s | %s | %s | %s | %s | %s | %d/%d |" % (
            r["experiment"], r["fault_id"],
            "match" if r["location_match"] else "MISMATCH",
            "match" if r["signal_match"] else "MISMATCH",
            "CORRECT" if r["diagnosis_correct"] else "INCORRECT",
            "match" if r["first_failure_match"] else "MISMATCH",
            r["evidence_verified"], r["evidence_total"]))
    md += ["", "Correct diagnoses: **%d / %d**; evidence entries verified: %d / %d." % (
        summary["correct_diagnoses"], len(faults), summary["evidence_verified"],
        summary["evidence_total"]), ""]
    for r in results:
        md += ["## %s" % r["experiment"], "", md_section(r)]
    with open(os.path.join(REPORTS, "evaluation.md"), "w") as f:
        f.write("\n".join(md))

    # Append / refresh the separate evaluation section in each agent report.
    for r in results:
        p = os.path.join(REPORTS, r["experiment"] + ".md")
        if not os.path.isfile(p):
            continue
        with open(p) as f:
            body = f.read().split(EVAL_MARK)[0].rstrip()
        with open(p, "w") as f:
            f.write(body + "\n\n" + EVAL_MARK + "\n\n## Evaluation against injected fault\n\n"
                    + md_section(r))

    for line in md[4:4 + 2 + len(results)]:
        print(line)
    print("correct=%d/%d  incorrect=%s  first_failure_matches=%d  evidence_verified=%d/%d"
          % (summary["correct_diagnoses"], len(faults), summary["incorrect_diagnoses"] or "none",
             summary["first_failure_matches"], summary["evidence_verified"],
             summary["evidence_total"]))
    integrity_ok = (len(evaluated) == len(faults)
                    and summary["evidence_verified"] == summary["evidence_total"])
    print("eval: %s" % ("OK" if integrity_ok else
                        "INTEGRITY PROBLEM (missing/malformed report or unverifiable evidence)"))
    return 0 if integrity_ok else 1


if __name__ == "__main__":
    sys.exit(main())
